#!/usr/bin/env python3
"""Write the prompts of the large graphics tasks to prompts/, to run them in another API, chat or agent harness
and compare the answers with the local models (grade them with run_eval.py --from-file).

    python make_prompts.py

prompts/<task_id>.md          system + user prompt, with how to send it and how to grade the answer
prompts/<task_id>.system.txt  the system prompt alone (for an API call)
prompts/<task_id>.user.txt    the user prompt alone
Generated from the task files, so they always match what the local models get. Run again after a task changes.
"""
from pathlib import Path

import tasks as T
import tasks_engineering as TEN
import tasks_scene as TSC

HERE = Path(__file__).resolve().parent
OUT = HERE / "prompts"
JOBS = [("scene", TSC, "s1_ocean_island"), ("engineering", TEN, "e1_watch_unitas"),
        ("engineering", TEN, "e2_rocket_launch")]
LIMITS = {"scene": "60 min and 98,304 tokens", "engineering": "120 min and 196,608 tokens"}


def three_version():
    import json
    pkg = HERE / "ts_env" / "node_modules" / "three" / "package.json"
    try:
        return json.loads(pkg.read_text(encoding="utf-8"))["version"]
    except Exception:
        return "the latest release"


def page(suite, task, system):
    tid = task["id"]
    w, h = task.get("viewport", (1280, 720))
    return f"""# {tid}: prompt for comparisons

Suite `{suite}` ([README](../README.md)). Send the **system** and the **user** prompt below unchanged, as two
messages (or, where the tool has no system prompt, the system text first and then the user text in one message).
The local models get exactly this, with {LIMITS[suite]} per task.

How the answer is run: one TypeScript file, bundled with esbuild against Three.js {three_version()}
(`three` and `three/addons/...`), compiled with `tsc --strict`, opened in Chromium at {w} x {h}
with a software WebGL renderer (SwiftShader).

**Chat or API:** save the whole reply as `{tid}.md` (the ```ts block is taken from it).
**Agent harness** (Claude Code, Codex, Cursor and the like): add one line to the user prompt,
"Write the file to main.ts instead of replying with a code block.", then save it as `{tid}.ts`.
Do not let the agent install other packages or add an HTML file: only the TypeScript file is used.

Grade it like a local run (it goes to the same tables and gallery):

```
python run_eval.py --suite {suite} --tasks {tid} --from-file answers/ --label <Model-Name>-<harness>
```

Optional `answers/{tid}.json` with `{{"minutes": 12.5, "tokens": 48000, "reasoning_tokens": 30000}}` adds time and
tokens to the tables.

## System prompt

```text
{system.strip()}
```

## User prompt

```text
{task["prompt"].strip()}
```
"""


def main():
    OUT.mkdir(exist_ok=True)
    index = ["# Prompts for comparisons", "",
             "The large graphics tasks as plain prompts, to run in another API, chat or agent harness. "
             "Generated by `python make_prompts.py` from the task files.", "",
             "| Task | Suite | Prompt | System / user (plain text) |", "|---|---|---|---|"]
    for suite, mod, tid in JOBS:
        task = next(t for t in mod.THREE_TASKS if t["id"] == tid)
        system = task.get("system") or T.THREE_SYSTEM
        (OUT / f"{tid}.md").write_text(page(suite, task, system), encoding="utf-8")
        (OUT / f"{tid}.system.txt").write_text(system.strip() + "\n", encoding="utf-8")
        (OUT / f"{tid}.user.txt").write_text(task["prompt"].strip() + "\n", encoding="utf-8")
        index.append(f"| {tid} | {suite} | [{tid}.md]({tid}.md) | [system]({tid}.system.txt), [user]({tid}.user.txt) |")
    (OUT / "README.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
